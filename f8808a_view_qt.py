"""Fluke 8808A performance verification: the Qt window code (port of the removed Tk view f8808a_view_tk.py: same functions, same widgets as attributes of the App, same texts, same busy /
idle button states).

The engine reaches this module through `ui_port.get_ui().view('f8808a_view')`, which resolves to `f8808a_view_qt` under the Qt port.  Every function takes the engine's App
as `self` and keeps its widgets as attributes of it (`self.tree`, `self.btn_run`, ... the shared mixins, manual_override among them, use them too).  The parts the bench
windows share are qtui/bench_view.py.  Nothing here decides anything about a calibration.
"""
from qtui import bench_view as B
from qtui import shell as S
from qtui.bench_view import Form, table_has, table_select, table_selection, table_set_rows, table_update_row  # noqa: F401  (the table_* contract of the views)


def setup_window(self):
    """Theme, title and size of the main window (statements of the engine's former App.__init__)."""
    import fluke8808a_verification as E
    B.setup_window(self, f'Fluke {E.MODEL} | Performance Verification' + (' [DEMO]' if self.demo else ''), 1340, 860, 900, 660)


def finish_window(self):
    """Attach the asset-history helpers to the window (the last statements of the engine's former App.__init__)."""
    B.finish_window(self)


def sync_buttons(self):
    B.sync_buttons(self, (self.btn_run, self.btn_section, self.btn_rerun, self.btn_test, self.btn_load, self.btn_find), [(self.period_combo, 'readonly')])


def build_ui(self):
    import fluke8808a_verification as E                      # the engine's module state (configure(model) can rebind it), read at call time
    BAUDS, MODEL, PARITY_FORMATS, PERIODS, POINTS, SPEC, WARM_UP, list_com_ports = E.BAUDS, E.MODEL, E.PARITY_FORMATS, E.PERIODS, E.POINTS, E.SPEC, E.WARM_UP, E.list_com_ports
    root = self.root
    sh = self.shell = S.Shell(root, f'Fluke {MODEL}  -  Performance Verification',
                              f'Calibration Manual Tables 3-2 to 3-8, pp. 3-4 to 3-11  |  {len(POINTS)} points in the spec  |  RS-232 only', demo=self.demo,
                              on_section=self.pick_section, version='spec v1')
    self.status = sh.status_var
    self.conn_pill = sh.add_chip('Not connected', 'neutral')
    sh.build_identity(self.asset, self.serial)
    self.build_mode_segment(sh.strip, notice_holder=sh.notice_holder)
    self.summary = sh.build_progress()
    B.notice(sh, self, 'The program pauses and shows the hook-up for every new setup and asks to confirm high voltage once per hook-up group. ' + WARM_UP
             + ' Stay at the bench while a run is in progress.',
             demo_text='Results are generated by the program and are NOT calibration evidence. Reports are marked as demo data.', demo_title='Demo mode')

    f = Form(sh.drawer_body)
    self.period_combo = f.row('Limits to apply', f.combo(self.period, list(PERIODS), 20, command=self.on_period))
    f.note('90 days is for an acceptance test after a calibration; the manual recommends a one-year interval.')
    f.rule()
    self.dmm_entry = f.row('8808A COM port', f.combo(self.dmm_addr, list_com_ports(), 14, state='normal'))
    for text, var, values, width in (('Baud', self.dmm_baud, BAUDS, 9), ('Format', self.dmm_format, list(PARITY_FORMATS), 24)):
        f.row(text, f.combo(var, values, width))
    f.note('Factory settings: 9600 baud, 8 data bits, no parity, 1 stop bit, Echo OFF (Users Manual Table 4-1). They are set from the meter front panel only. '
           'Echo must stay off. The 8808A has no GPIB or USB port.')
    calbox = f.row('Calibrator', f.combo(self.cal_model, self.cal_choices(), 14))
    B.calibrator_note(f, self.cal_offer, widgets=(calbox,))
    self.cal_entry = f.row('Calibrator address', f.combo(self.cal_addr, (), 34, state='normal'), fill=True)
    f.row('Calibrator baud', f.combo(self.cal_baud, ['9600', '19200', '4800', '2400', '1200'], 9))
    f.note('COM9, GPIB0::6::INSTR ...', column=1)
    B.find_and_test(sh, self, 'Refresh ports', self.find_instruments)

    B.action_bar(self, sh, manual=True)
    B.build_results(self, sh, SPEC['source']['note'])
    self.update_shell_sections(POINTS, lambda p: p['section_title'])


def set_choices(self, which, values):
    """The drop-down values of the DMM port ('dmm') or calibrator port ('cal') box."""
    (self.dmm_entry if which == 'dmm' else self.cal_entry).configure(values=values)
