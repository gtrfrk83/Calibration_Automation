"""Demo mode = the VIRTUAL BENCH (Tk-free; nothing here draws a window).

Until now `--demo` generated the readings itself, sent no commands and showed none of the operator's windows.  Now a demo run behaves like a real
run with VIRTUAL instruments connected: the same connection step, reset notice, hook-up / function / HV prompts, reading entry window and
per-point windows appear, and every command goes through the REAL driver code over the simulated transports of drivers/simulated*.py (set, read
back, compare, error queue, standby after each point).  What stays different is only what must stay different:

  * everything is DEMO: window title '[DEMO]', the banner, the 'Demo - virtual instruments' chip, every result record carries synthetic=True,
    the report PDF is stamped DEMO DATA on every page, and nothing reaches Asset History / the lab registry / the shared command log;
  * long settle waits are shortened (WAIT_SCALE); the dialogs are not;
  * a handheld reading window gets a clearly marked 'Fill with a simulated reading (DEMO)' button; the operator may type anything instead.

`--fast-demo` (with or without `--demo`) keeps the old quick behaviour: readings generated by the program, no windows, no commands.

Engines use VirtualMixin: `self.demo` (any demo), `self.fast_demo` (the old behaviour), `self.virtual` (the virtual bench).  An object that has only a
`demo` attribute (older tests build such objects) is treated as fast demo, exactly as before.
"""
from __future__ import annotations

import math
import sys
from decimal import Decimal

from drivers import simulated as _sim

CHIP = 'Demo - virtual instruments'
MODE_CHIP = 'DEMO MODE  -  virtual instruments'
FAST_CHIP = 'Demo - no hardware'
BANNER_TITLE = 'Demo mode'
BANNER = ('Virtual instruments are connected: commands go through the real drivers to simulated instruments, and every window of a real run appears. '
          'Nothing here is calibration evidence; reports are marked as demo data and are not recorded in Asset History.')
FAST_BANNER = 'Results are generated by the program and are NOT calibration evidence. Reports are marked as demo data.'
FILL_TEXT = 'Fill with a simulated reading (DEMO)'
VIRTUAL_TAG = '[VIRTUAL - simulated instrument]'

WAIT_SCALE = 0.02          # settle / ramp waits in a virtual run are this fraction of the real wait (dialogs are never skipped)
WAIT_FLOOR = 0.02


def flags(argv=None):
    """(demo, fast_demo) from a command line.  --fast-demo implies demo."""
    argv = sys.argv if argv is None else argv
    fast = '--fast-demo' in argv
    return ('--demo' in argv or fast), fast


def scaled(seconds, virtual):
    """A wait in seconds: unchanged for a real run, shortened for the virtual bench."""
    return max(WAIT_FLOOR, seconds * WAIT_SCALE) if virtual and seconds > 0 else seconds


class VirtualMixin:
    """demo / fast_demo / virtual for an App.  `_fast_demo` is set by the constructor; an object without it keeps the old quick demo."""

    @property
    def fast_demo(self) -> bool:
        return bool(getattr(self, 'demo', False)) and bool(getattr(self, '_fast_demo', True))

    @property
    def virtual(self) -> bool:
        return bool(getattr(self, 'demo', False)) and not self.fast_demo

    def init_virtual(self, demo, fast_demo=False):
        self._fast_demo = bool(fast_demo)
        try:
            import ui_theme
            ui_theme.DEMO_SUFFIX = ' [DEMO]' if (demo and not fast_demo) else ''
        except Exception:
            pass
        self._vb = None                 # (bench, calibrator transport, DMM transport) of the virtual bench once connected
        self.demo_failures = None       # a tk.BooleanVar once the window exists: 'include some failures' for the simulated fill
        self.demo_failures_on = False

    def virtual_failures(self) -> bool:
        v = getattr(self, 'demo_failures', None)
        try:
            return bool(v.get()) if v is not None else bool(getattr(self, 'demo_failures_on', False))
        except Exception:
            return bool(getattr(self, 'demo_failures_on', False))

    def chip_text(self) -> str:
        return CHIP if self.virtual else FAST_CHIP

    def banner_text(self) -> str:
        return BANNER if self.virtual else FAST_BANNER


def mark_log(log):
    """A virtual run's command log is never appended to the shared evidence file (~/.calibration_suite/command_log.txt)."""
    if log is not None:
        log.virtual = True
    return log


def log_is_virtual(log) -> bool:
    return bool(getattr(log, 'virtual', False))


# ------------------------------------------------------------------------------------------------------- simulated readings for a typed value
def _places(low, high):
    return max(-low.as_tuple().exponent, -high.as_tuple().exponent, 0)


def failing_point(key, include_failures) -> bool:
    """Deterministic 'seeded' mix: with the toggle on, roughly one point in six (by point number) is filled just outside its limit."""
    if not include_failures:
        return False
    try:
        n = int(key)
    except (TypeError, ValueError):
        n = sum(ord(c) for c in str(key))
    return (n * 7 + 3) % 6 == 0


def plausible_text(low, high, n, include_failures=False, places=None):
    """A reading inside [low, high] (Decimal-exact), deterministic in n; with include_failures some points are filled just outside the limits.
    The text carries the limits' number of decimals.  Same formula as the old generated demo, so the numbers are familiar."""
    low, high = Decimal(str(low)), Decimal(str(high))
    places = _places(low, high) if places is None else places
    mid, half = (low + high) / 2, (high - low) / 2
    if failing_point(n, include_failures):
        sign = 1 if (int(n) if str(n).lstrip('-').isdigit() else 0) % 2 else -1
        value = mid + sign * half * Decimal('1.6')
        step = Decimal(1).scaleb(-places)
        if half < step:                                   # a hair-thin window: a whole display step outside
            value = (high + step) if sign > 0 else (low - step)
    else:
        value = mid + half * Decimal(str(round(math.sin(float(n if str(n).lstrip('-').isdigit() else sum(ord(c) for c in str(n))) * 1.71) * 0.38, 4)))
    return f'{value:.{places}f}'


def plausible_answer(key, include_failures=False) -> bool:
    """For a yes/no point: yes (the instrument behaves as stated) unless the failure mix chooses this point."""
    return not failing_point(key, include_failures)


# ---------------------------------------------------------------------------------------------------------------- simulated transports
def sim_model(text):
    """'5522A' / '5520A' / '5560A' from a calibrator choice text (the 5560A when it cannot be told): the model the simulated calibrator introduces itself as."""
    t = str(text)
    return '5522A' if '5522' in t else '5520A' if '5520' in t else '5560A'


def calibrator_transport(model):
    """Simulated Fluke 5522A / 5520A / 5560A for the handheld, DAQ and DMM engines (its own private bench)."""
    bench = _sim.SimBench()
    t = _sim.SimFlukeTransport(bench, sim_model(model))
    t.opened = False
    return bench, t


def dmm_pair(model, cal='5560A'):
    """(bench, calibrator transport, DMM transport) for 34401A / 8846A / Truevolt."""
    bench, ft, dt = _sim.make_dmm_bench(model)
    bench.freq_aware = True
    ft.model = sim_model(cal)
    return bench, ft, dt


def dacq_pair(model, cal='5560A', modules=None):
    return _sim.make_dacq_bench(model, sim_model(cal), modules)


def status_text(app) -> str:
    """The status-bar text of a demo window."""
    if app.virtual:
        return ('DEMO MODE (virtual instruments): the windows of a real run appear and commands go to simulated instruments. '
                'Enter an Instrument ID, then press Run All.')
    return 'FAST DEMO: no commands are sent to any instrument and no windows are shown. Enter an Instrument ID, then press Run All.'


def operator_sets_up(vb, p, terminal=None, manual=False, nominal=None):
    """What the operator does after a hook-up prompt, done for them on the simulated bench: set the Front/Rear switch the point needs and, for a
    point measured against a standard the technician connects (no calibrator), connect it (the DMM then reads its nominal).
    vb = (bench, calibrator transport, DMM transport) from dmm_pair / dacq_pair; None before a connection exists."""
    if not vb:
        return
    bench, _cal, dmm = vb
    if terminal is not None:
        dmm.terminals = 'REAR' if terminal == 'REAR' else 'FRON'
    bench.external_input = float(nominal) if (manual and nominal is not None) else None


def fgen_operator_sets_up(vb, group):
    """The virtual operator cables the generator output to the reference the hook-up prompt named (function-generator bench)."""
    if not vb:
        return
    bench = vb[0]
    bench.connected = {'COUNTER': 'counter', 'STD': 'std', 'WBND': 'wbnd', 'POWER': 'power', 'POWER_ATT': 'power'}.get(group, bench.connected)
    bench.attenuator = group == 'POWER_ATT'


def fgen_typed_value(vb, unit):
    """A plausible reading for a reference the technician reads by hand (no address given), taken from the simulated generator's output."""
    import math
    if not vb:
        return None
    b = vb[0]
    if unit == 'Hz':
        return b.gen['freq'] * (1 + b.ppm) * (1 + b.ppm_counter)
    if unit == 'dBm':
        v = b.vrms_into(50.0)
        return round(10 * math.log10(v * v / 50.0 / 1e-3) - (20.0 if b.attenuator else 0.0), 3) if v > 0 else -70.0
    return None


def mdo_operator_confirmed(vb, title):
    """After an MDO4000C hook-up prompt: the one thing the operator does on the front panel that no command can do - pushing the
    '250 kOhm Termination Verification' button - is done on the simulated scope."""
    if vb and title in ('250 kΩ termination', 'AUX IN'):
        vb.mdo['term'] = '250k'
