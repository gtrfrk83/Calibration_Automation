"""Writes specs/dmm6500_tar_below_4.md: the DMM6500 verification points whose TAR (UUT tolerance / calibrator published accuracy, tartur.py) is below 4:1, for each calibrator
the procedure can drive (5560A, 5700A, 5700A + 5725A; the 5520A and 5522A are not offered, owner 2026-11-03).  For the 5700A + 5725A the points made through the amplifier use the 5725A rows of the sheet.

TAR is the one the user asked for; the TUR (against the reported expanded uncertainty, max of budget and the lab's CMC) is listed beside it.  Points sourced by the manual's reference
DMM (1 ohm and 10 ohm, 10 uA to 10 mA) are marked: the calibrator is not the standard there, so its TAR is shown but is not the deciding ratio.  A blank TAR means no specification
row of that calibrator covers the point (listed separately), never a pass.   Run:  python specs/analyze_dmm6500_tar.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import dmm6500_verification as E     # noqa: E402
import procspec                      # noqa: E402
import tartur                        # noqa: E402

CALS = ('5560A', '5700A', '5700A + 5725A')      # the 5520A and 5522A are not offered for this procedure (owner, 2026-11-03)
THRESHOLD = 4.0


def amp_row(p, q):
    """TAR of a point made through the 5725A amplifier, from the 5700A sheet's 5725A rows (specmanager variant '5725a'); None when no row covers it."""
    import specmanager as sm
    row = next((s for s in sm.standards() if s['model'] == '5700A'), None)
    std = sm.StandardSpec(row['id']) if row else None
    if std is None:
        return None
    hit = std.lookup(q['kind'], p['nominal'], p.get('frequency'), variant='5725a')
    if hit is None or not q['high'] > q['low']:
        return None
    tol = (q['high'] - q['low']) / 2
    return dict(tar=tol / hit.limit, tur=None, tolerance=tol, accuracy=hit.limit, uncertainty=None, reason='')


def _manual_5700a():
    import calibrator_fit
    offer = calibrator_fit.make_offer('5700A', calibrator_fit.dmm_requests(E.fit_requests(E.POINTS)), per_point_manual=True)
    return {r.key for r, _why in offer.manual}


def fmt(value, unit):
    return procspec._fmt(value, unit)


def ratio(x):
    return tartur.format_ratio(x) if x is not None else ''


def main():
    out = ['# DMM6500 verification: points with TAR below 4:1, per calibrator', '',
           'Generated by `specs/analyze_dmm6500_tar.py` from `specs/keithley_dmm6500_pv.json` and `tartur.py`. TAR = UUT tolerance (half-width of the limits) / calibrator published '
           '1-year accuracy at the point; TUR = tolerance / reported expanded uncertainty (k = 2). Ratios are rounded down to 0.1. Only points the calibrator sources are considered '
           '(zero checks with the 4-wire short and the manually set capacitance standard have no calibrator).', '',
           '**Reference-DMM points** (1 ohm, 10 ohm, 10 uA to 10 mA DC current) are marked `ref`: when a reference meter is connected the 3458A, not the calibrator, is the standard '
           'there, so the calibrator TAR shown is not the deciding ratio.', '']
    points = [p for p in E.POINTS if p['source'] == 'calibrator']
    summary = []
    sections = []
    for cal in CALS:
        low, blank = [], []
        base = cal.split(' + ')[0]
        amp_ids = E.amplifier_points([p for p in points if p['id'] in _manual_5700a()]) if '+' in cal else set()
        for p in points:
            q = E.effective(p)
            r = (amp_row(p, q) if p['id'] in amp_ids else None) or tartur.compute(q, q['low'], q['high'], standard=base)
            if r['tar'] is None:
                blank.append((p, r))
            elif r['tar'] < THRESHOLD:
                low.append((p, r))
        summary.append((cal, len(points), len(low), len(blank)))
        s = [f'## Fluke {cal}', '', f'{len(low)} of {len(points)} calibrator-sourced points are below {THRESHOLD:g}:1; {len(blank)} have no TAR (no specification row covers them).', '']
        if low:
            s += ['| Point | Test | Nominal | Tolerance (+/-) | Calibrator accuracy | TAR | TUR | Note |', '|---|---|---|---|---|---|---|---|']
            for p, r in sorted(low, key=lambda x: x[1]['tar']):
                nominal = fmt(p['nominal'], p['unit']) + (f" @ {fmt(p['frequency'], 'Hz')}" if p.get('frequency') and p['kind'] != 'FREQ' else '')
                s.append(f"| {p['ref']} | {p['section_title']}: {p['desc']} | {nominal} | {fmt(r['tolerance'], p['unit'])} | {fmt(r['accuracy'], p['unit'])} | {ratio(r['tar'])} | {ratio(r['tur'])} | "
                         f"{'ref' if p.get('ref_dmm') else ''} |")
            s.append('')
        if blank:
            s += ['No TAR (reason):', '']
            for p, r in blank:
                s.append(f"- {p['ref']} {p['section_title']}: {p['desc']} - {r['reason']}")
            s.append('')
        sections.append('\n'.join(s))
    out += ['| Calibrator | Sourced points | TAR < 4:1 | No TAR |', '|---|---|---|---|'] + [f'| {c} | {n} | {a} | {b} |' for c, n, a, b in summary] + ['']
    out += sections
    path = HERE / 'dmm6500_tar_below_4.md'
    path.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'wrote {path.name}: ' + '; '.join(f'{c} {a}/{n} below 4:1 ({b} without a TAR)' for c, n, a, b in summary))


if __name__ == '__main__':
    main()
