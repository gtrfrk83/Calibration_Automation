"""Which calibrators can source the Keithley 2000 adjustment? Writes specs/k2000_adjustment_standards.md.

    python specs/analyze_k2000_adjustment_standards.py

Two comparisons per adjustment step and per calibrator (5522A, 5520A, 5560A), from the specification rows the suite already holds (specs/standards/*.json, loaded into a PRIVATE
temporary database so a stale lab_registry.sqlite3 cannot change the result):

  1. Against the manual's own requirement, Table 2-1 (p. 2-6): the Fluke 5700A's 90-day accuracy at each step, as printed in ppm.  "Alternate equipment ... as long as that
     equipment has specifications at least as good as those listed in the table" (p. 2-6).  The calibrator's specification at the step (its absolute accuracy converted to ppm
     of the output) is divided by the printed ppm: a ratio of 1.0 or less meets the manual's requirement.  The 5520A sheet carries a 90-day column (used); the 5522A and 5560A
     sheets hold the 1-year column only, which is LARGER than a 90-day figure (conservative: the true 90-day ratio is better than shown).  Confidence levels differ (5522A / 5520A
     99 %, 5560A 95 %, k = 2 column); none is converted.
  2. TAR against the 2000's own 1-year verification limit (specs/keithley_2000_pv.json) at the same point where the verification has one (the 10 mV AC, 100 mA AC and 2 A AC
     adjustment points have no verification point): limit / calibrator accuracy.

The table is advice for the lab's own decision; the program offers every calibrator whose driver exists and says in the window which Table 2-1 ratios exceed 1.
"""
import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))
try:
    import tkinter  # noqa: F401
except ImportError:
    sys.path.insert(0, str(ROOT / 'tests'))
    import _tk_stub
    _tk_stub.install()
import procspec
import specmanager as sm

sm.DB = Path(tempfile.mkdtemp(prefix='k2000adj_')) / 'standards.sqlite3'
sm.seed()

OUT = HERE / 'k2000_adjustment_standards.md'
CALS = ('5522A', '5520A', '5560A')
ADJ = json.loads((HERE / 'keithley_2000_adjustment.json').read_text(encoding='utf-8'))
PV = procspec.flatten(procspec.load(HERE / 'keithley_2000_pv.json'))
UNITS = {'V': 1.0, 'mV': 1e-3, 'A': 1.0, 'mA': 1e-3, 'kohm': 1e3, 'Mohm': 1e6}
KIND = {'DCV': 'DCV', 'ACV': 'ACV', 'DCI': 'DCI', 'ACI': 'ACI', 'OHM': 'OHM4'}
TABLE_2_1 = {}                    # (function, nominal in base units, frequency or None) -> printed ppm
for fn, rows in ADJ['equipment']['ppm'].items():
    for value, unit, freq, ppm in rows:
        for f in ([None] if not freq else [1000.0, 50000.0] if '50 kHz' in freq else [1000.0]):
            TABLE_2_1[(fn, float(value) * UNITS[unit], f)] = ppm


def accuracy(model, kind, value, freq, period=None):
    std = sm.standard(model)
    hit = std.lookup(KIND[kind], abs(value), frequency=freq, period=period)
    if hit is None and period:
        hit = std.lookup(KIND[kind], abs(value), frequency=freq)
    return None if hit is None else (hit.limit, hit.period)


def pv_limit(kind, value, freq):
    k = {'OHM': 'OHM4'}.get(kind, kind)
    for p in PV:
        if p['kind'] == k and abs(abs(p['nominal']) - abs(value)) < 1e-12 and (p.get('frequency') or None) == freq:
            return p['limits']['1y']
    return None


def main():
    rows = []
    for s in ADJ['steps']:
        src = s['source']
        if not src:
            continue
        value = float(src['value'])
        freq = float(src['frequency']) if src.get('frequency') else None
        kind = src['kind']
        printed = TABLE_2_1.get((kind, abs(value), freq))
        limit = pv_limit(kind, value, freq)
        cells = {}
        for m in CALS:
            got = accuracy(m, kind, value, freq, '90 day' if m == '5520A' else None)
            if got is None:
                cells[m] = None
                continue
            acc, period = got
            ppm = acc / abs(value) * 1e6
            cells[m] = dict(acc=acc, ppm=ppm, period=period, ratio=(ppm / printed if printed else None), tar=(limit / acc if limit else None))
        rows.append((s, value, freq, printed, limit, cells))
    L = []
    w = L.append
    w('# Keithley 2000 adjustment: which calibrator can source it')
    w('')
    w('Generated by `specs/analyze_k2000_adjustment_standards.py`. Do not edit by hand.')
    w('')
    w('* **Ratio** = the calibrator\'s specification at the step, in ppm of the output, divided by the ppm the manual prints for the Fluke 5700A in Table 2-1 (p. 2-6, 90-day). '
      'The manual allows alternate equipment "as long as that equipment has specifications at least as good as those listed in the table": **1.0 or less meets it**.')
    w('* **TAR (1y)** = the 2000\'s 1-year verification limit at the same point (`keithley_2000_pv.json`) / the calibrator\'s accuracy; "-" where the verification has no such point.')
    w('* 5520A: the 90-day column of its sheet. 5522A / 5560A: the sheets hold the 1-year column only (larger than a 90-day figure, so their ratios are conservative). '
      'Confidence levels are not converted (5522A / 5520A 99 %, 5560A 95 %).')
    w('')
    w('| Step | Output | Table 2-1 ppm | ' + ' | '.join(f'{m} ppm / ratio / TAR' for m in CALS) + ' |')
    w('|---|---|---|' + '---|' * len(CALS))
    verdict = {m: [] for m in CALS}
    for s, value, freq, printed, limit, cells in rows:
        out = f'{value:g} {s["source"]["unit"]}' + (f' @ {freq / 1000:g} kHz' if freq else '')
        parts = []
        for m in CALS:
            c = cells[m]
            if c is None:
                parts.append('not specified')
                verdict[m].append((s['id'], None))
                continue
            parts.append(f'{c["ppm"]:.1f} / {c["ratio"]:.2f} / ' + (f'{c["tar"]:.1f}' if c['tar'] else '-'))
            verdict[m].append((s['id'], c['ratio']))
        w(f'| {s["id"]} {s["title"]} | {out} | {printed} | ' + ' | '.join(parts) + ' |')
    w('')
    w('## Steps whose ratio is above 1.0 (the calibrator does not meet Table 2-1 at that step) or that the sheet does not cover')
    w('')
    for m in CALS:
        bad = [f'{i} ({r:.2f})' if r is not None else f'{i} (not specified)' for i, r in verdict[m] if r is None or r > 1.0]
        w(f'* **{m}**: ' + (', '.join(bad) if bad else 'none'))
    w('')
    w('Read this as information for the lab\'s own decision (which standard adjusts a Model 2000, and with what uncertainty). Nothing here changes what the program does: it offers the '
      '5560A, 5522A and 5520A and prints the ratios above in the "Standards" note of the window.')
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    summary = {m: sum(1 for _i, r in verdict[m] if r is not None and r <= 1.0) for m in CALS}
    print(f'wrote {OUT.name}: steps meeting Table 2-1 (of {len(rows)}): {summary}')


if __name__ == '__main__':
    main()
