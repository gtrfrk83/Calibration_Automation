"""Which calibrators can source the Fluke 8808A adjustment? Writes specs/8808a_adjustment_standards.md.

    python specs/analyze_8808a_adjustment_standards.py

Per sourced adjustment step and per calibrator (5522A, 5520A, 5560A), from the specification rows the suite already holds (specs/standards/*.json, loaded into a PRIVATE
temporary database so a stale lab_registry.sqlite3 cannot change the result):

  1. Coverage (calibrator_fit): does the calibrator's published specification have a row for the output? The only step none of the three can source is S054 (1.9 V at 750 kHz).
  2. TAR against the 8808A's own 1-year verification limit (specs/fluke_8808a_pv.json) at the SAME point where the verification has one: half the limit window / the calibrator's
     1-year accuracy. The adjustment points are not all verification points (the 8808A verification has 105 points, the adjustment 124 steps), so "-" is common.
  3. The manual's own two numeric requirements (Table 3-1, p. 3-3): the resistance standard "accuracy better than 0.0045 %" (45 ppm) and the frequency source "better than 0.0025 %"
     (25 ppm). The manual prints NO ppm table for voltage or current (it names the Fluke 5700A / 5725A), so there is no manual ratio to compute there. The resistance column
     below is the calibrator's accuracy in ppm of the output against 45 ppm; the frequency requirement is NOT checked, because the suite's sheets hold no frequency accuracy.

The table is advice for the lab's own decision; the program offers every calibrator whose driver exists and prints the coverage in the window.
"""
import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))
import calibrator_fit
import specmanager as sm

sm.DB = Path(tempfile.mkdtemp(prefix='8808adj_')) / 'standards.sqlite3'
sm.seed()

OUT = HERE / '8808a_adjustment_standards.md'
CALS = ('5522A', '5520A', '5560A')
ADJ = json.loads((HERE / 'fluke_8808a_adjustment.json').read_text(encoding='utf-8'))
PV = json.loads((HERE / 'fluke_8808a_pv.json').read_text(encoding='utf-8'))
PV_POINTS = [p for sec in PV['sections'] for p in sec['points']]
KIND = {'DCV': 'DCV', 'ACV': 'ACV', 'DCI': 'DCI', 'ACI': 'ACI'}
OHM_PPM_LIMIT = 45.0        # 0.0045 % (Table 3-1 p. 3-3)


def accuracy(model, kind, value, freq):
    std = sm.standard(model)
    hit = std.lookup(kind, abs(value), frequency=freq)
    return None if hit is None else hit.limit


def pv_halfwindow(kind, value, freq, wire):
    for p in PV_POINTS:
        k = p['kind']
        if k in ('OHM2', 'OHM4'):
            ok = kind == 'OHM' and k == ('OHM4' if wire == 4 else 'OHM2')
        else:
            ok = k == kind
        if ok and abs(abs(p['nominal']) - abs(value)) < 1e-12 and (p['frequency'] or None) == freq:
            lim = p['limits']['1y']
            return (lim['high'] - lim['low']) / 2
    return None


def main():
    fit = {m: calibrator_fit.assess(m, __import__('fluke8808a_adjustment').requests()) for m in CALS}
    rows = []
    for s in ADJ['steps']:
        src = s['source']
        if not src:
            continue
        value = float(src['value'])
        freq = float(src['frequency']) if src.get('frequency') else None
        kind = src['kind']
        half = pv_halfwindow(kind, value, freq, s['wire'])
        cells = {}
        for m in CALS:
            k = {'OHM': 'OHM4'}.get(kind, kind)
            acc = accuracy(m, k, value, freq)
            if acc is None:
                cells[m] = None
                continue
            ppm = acc / abs(value) * 1e6 if value else None
            cells[m] = dict(acc=acc, ppm=ppm, tar=(half / acc if half else None))
        rows.append((s, value, freq, half, cells))
    L = []
    w = L.append
    w('# Fluke 8808A adjustment: which calibrator can source it')
    w('')
    w('Generated by `specs/analyze_8808a_adjustment_standards.py`. Do not edit by hand.')
    w('')
    w('* **Coverage** is `calibrator_fit`: every output of the adjustment against the calibrator\'s published specification rows. 119 of the 124 steps need a calibrator output (the five zero points - DC volts and ohms with the 4-wire short, AC volts with the calibrator in standby, the two current zeros with open inputs - need none; the zero ohm point uses the 4-wire short, lab policy). ' + '; '.join(
        f'{m}: {len(fit[m].excluded)} excluded' for m in CALS) + '. The excluded step is the one that needs 750 kHz (S054, 1.9 V): the operator connects another standard there.')
    w('* **ppm** = the calibrator\'s 1-year specification at the step in ppm of the output (the sheets hold the 1-year column). Confidence levels differ (5522A / 5520A 99 %, 5560A 95 %) and are not converted.')
    w('* **TAR (1y)** = half of the 8808A\'s 1-year verification limit window at the same point (`fluke_8808a_pv.json`) / the calibrator\'s accuracy; "-" where the verification has no such point.')
    w('* The manual (Table 3-1, p. 3-3) prints no ppm table for volts and current; it names the Fluke 5700A / 5725A. For resistance it requires accuracy better than 0.0045 % (**45 ppm**); for frequency better than 0.0025 % (25 ppm, NOT checked: no frequency accuracy in the sheets).')
    w('')
    w('| Step | Output | ' + ' | '.join(f'{m} ppm / TAR' for m in CALS) + ' |')
    w('|---|---|' + '---|' * len(CALS))
    ohm_bad = {m: [] for m in CALS}
    missing = {m: [] for m in CALS}
    for s, value, freq, half, cells in rows:
        out = f'{value:g} {s["source"]["unit"]}' + (f' @ {freq / 1000:g} kHz' if freq else '')
        parts = []
        for m in CALS:
            c = cells[m]
            if c is None:
                parts.append('not specified')
                missing[m].append(s['id'])
                continue
            ppm = f'{c["ppm"]:.1f}' if c['ppm'] is not None else '-'
            parts.append(f'{ppm} / ' + (f'{c["tar"]:.1f}' if c['tar'] else '-'))
            if s['source']['kind'] == 'OHM' and c['ppm'] is not None and c['ppm'] > OHM_PPM_LIMIT:
                ohm_bad[m].append(f'{s["id"]} ({c["ppm"]:.0f} ppm)')
        w(f'| {s["id"]} {s["function"]} {s["title"]} | {out} | ' + ' | '.join(parts) + ' |')
    w('')
    w('## Resistance steps above the manual\'s 45 ppm requirement, and steps the sheet does not cover')
    w('')
    for m in CALS:
        w(f'* **{m}**: resistance above 45 ppm: ' + (', '.join(ohm_bad[m]) if ohm_bad[m] else 'none') + '; not specified: ' + (', '.join(missing[m]) if missing[m] else 'none'))
    w('')
    w('Read this as information for the lab\'s own decision. Nothing here changes what the program does: it offers the 5522A, 5560A and 5520A and shows the coverage in the "Calibrator" note of the window. '
      'The manual also says four ranges (200 uA, 2000 uA, 200 mA, 2 A DC) need the calibrator characterized (it names an 8508A; this lab uses a Keysight / Agilent 3458A, which has NO standards sheet or driver in the suite, so it is a text mention only and no specification is assumed): the program asks for the value measured with the 3458A at those steps.')
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(f'wrote {OUT.name}: {len(rows)} sourced steps; ' + ', '.join(f'{m} not specified {len(missing[m])}, resistance >45 ppm {len(ohm_bad[m])}' for m in CALS))


if __name__ == '__main__':
    main()
