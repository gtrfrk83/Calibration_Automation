"""HP 8591A performance verification: the Qt window code (the same functions and widgets as fluke6060a_view_qt.py, which this follows: widgets are attributes of the engine's App, the shared
mixins, manual_override among them, use them too).  The parts the bench windows share are qtui/bench_view.py.  Nothing here decides anything about a calibration.
"""
from qtui import bench_view as B
from qtui import shell as S
from qtui import shell_helpers as H
from qtui.bench_view import Form, table_has, table_select, table_selection, table_set_rows, table_update_row  # noqa: F401  (the table_* contract of the views)


def setup_window(self):
    """Theme, title and size of the main window."""
    import hp8591a_verification as E
    B.setup_window(self, f'HP {E.MODEL} | Performance Verification' + (f' ({E.VARIANT_LABEL})' if E.VARIANT_LABEL else '') + (' [DEMO]' if self.demo else ''), 1340, 860, 900, 660)


def finish_window(self):
    """Attach the asset-history helpers to the window."""
    B.finish_window(self)


def sync_buttons(self):
    B.sync_buttons(self, (self.btn_run, self.btn_section, self.btn_rerun, self.btn_test, self.btn_load, self.btn_find), [(self.opt_check, B.idle_state(self.opt_check))])


def build_ui(self):
    import hp8591a_verification as E                      # the engine's module state, read at call time
    MODEL, POINTS, SPEC, WARM_UP = E.MODEL, E.POINTS, E.SPEC, E.WARM_UP
    root = self.root
    sh = self.shell = S.Shell(root, f'HP {MODEL}  -  Performance Verification' + (f' ({E.VARIANT_LABEL})' if E.VARIANT_LABEL else ''),
                              f'T.O. 33K3-4-2864-1 (3.3, 4.1 to 4.12)  |  {len(POINTS)} points in the spec  |  GPIB', demo=self.demo, on_section=self.pick_section, version='spec v1')
    self.status = sh.status_var
    self.conn_pill = sh.add_chip('Not connected', 'neutral')
    sh.build_identity(self.asset, self.serial)
    self.build_mode_segment(sh.strip, notice_holder=sh.notice_holder)
    self.summary = sh.build_progress()
    B.notice(sh, self, 'The program resets both instruments, pauses for the hook-up of every new setup, asks you to disconnect the NRP40T for its zero and switches the 96270A output off after every point. '
             'It sends no calibration command to the analyzer: the self-calibration is yours to run from the front panel. ' + WARM_UP + ' Stay at the bench while a run is in progress.',
             demo_text='Results are generated by the program and are NOT calibration evidence. Reports are marked as demo data.', demo_title='Demo mode')

    f = Form(sh.drawer_body)
    self.uut_entry = f.row('8591A GPIB address', f.combo(self.uut_addr, (), 34, state='normal'), fill=True)
    f.note('The unit under test. 0 to 30 or GPIB0::n::INSTR. UNVERIFIED default: set the address the analyzer is really at.', column=1)
    self.rf_entry = f.row('96270A address / resource', f.combo(self.rf_addr, (), 34, state='normal'), fill=True)
    f.note('The signal source (leveled sine and AM) and, with the R&S NRP40T sensor, the power meter (4.1; the sensor is UNVERIFIED). Empty: the points that need it offer a typed reading.', column=1)
    f.rule()
    self.opt_check = f.wide(H.checkbutton(None, 'Unit has Option 004 (frequency reference)', self.opt004, self.on_options))
    f.note('Selects the CAL OUT frequency limits of 4.1.13 (299.999967 to 300.000033 MHz instead of 299.99925 to 300.00075 MHz). The other point is not run.')
    B.find_and_test(sh, self, 'Find instruments', self.find_instruments)

    B.action_bar(self, sh, manual=True)
    B.build_results(self, sh, SPEC['source']['note'])
    self.update_shell_sections(POINTS, lambda p: p['section_title'])


def set_choices(self, which, values):
    """The drop-down values of the 8591A ('uut') or 96270A ('rf') address box."""
    {'uut': self.uut_entry, 'rf': self.rf_entry}[which].configure(values=values)
