"""Fluke 6060A performance verification: the Qt window code (the same functions and widgets as bk5491b_view_qt.py / keysight_53220a_view_qt.py, which this follows: widgets are attributes of
the engine's App, the shared mixins, manual_override among them, use them too).  The parts the bench windows share are qtui/bench_view.py.  Nothing here decides anything about a calibration.
"""
from qtui import bench_view as B
from qtui import shell as S
from qtui import shell_helpers as H
from qtui.bench_view import Form, table_has, table_select, table_selection, table_set_rows, table_update_row  # noqa: F401  (the table_* contract of the views)


def setup_window(self):
    """Theme, title and size of the main window."""
    import fluke6060a_verification as E
    B.setup_window(self, f'Fluke {E.MODEL} | Performance Verification' + (' [DEMO]' if self.demo else ''), 1340, 860, 900, 660)


def finish_window(self):
    """Attach the asset-history helpers to the window."""
    B.finish_window(self)


def sync_buttons(self):
    B.sync_buttons(self, (self.btn_run, self.btn_section, self.btn_rerun, self.btn_test, self.btn_load, self.btn_find),
                   [(self.lf_combo, 'readonly'), (self.range_combo, 'readonly'), (self.thd_check, B.idle_state(self.thd_check))])


def build_ui(self):
    import fluke6060a_verification as E                      # the engine's module state (configure(model) can rebind it), read at call time
    LF_CHOICES, MODEL, POINTS, SPEC, TYPED_THD_TEXT, WARM_UP = E.LF_CHOICES, E.MODEL, E.POINTS, E.SPEC, E.TYPED_THD_TEXT, E.WARM_UP
    root = self.root
    sh = self.shell = S.Shell(root, f'Fluke {MODEL}  -  Performance Verification',
                              f'Instruction Manual, Section 4A (4A-3 to 4A-8, 4A-11, 4A-12)  |  {len(POINTS)} points in the spec  |  GPIB', demo=self.demo,
                              on_section=self.pick_section, version='spec v1')
    self.status = sh.status_var
    self.conn_pill = sh.add_chip('Not connected', 'neutral')
    sh.build_identity(self.asset, self.serial)
    self.build_mode_segment(sh.strip, notice_holder=sh.notice_holder)
    self.summary = sh.build_progress()
    B.notice(sh, self, 'The program resets every instrument, pauses for the hook-up of every new setup, asks for the three 8902A calibrations when they are first needed and switches the 6060A RF '
             'output off after every point. Output leakage (4A-9, 4A-10) is not part of this procedure. ' + WARM_UP + ' Stay at the bench while a run is in progress.',
             demo_text='Results are generated by the program and are NOT calibration evidence. Reports are marked as demo data.', demo_title='Demo mode')

    f = Form(sh.drawer_body)
    self.uut_entry = f.row('6060A GPIB address', f.combo(self.uut_addr, (), 34, state='normal'), fill=True)
    f.note('The unit under test. 0 to 30 or GPIB0::n::INSTR. The rear-panel switches set it; the owner\'s lab address is the default.', column=1)
    self.rx_entry = f.row('8902A GPIB address', f.combo(self.rx_addr, (), 34, state='normal'), fill=True)
    f.note('Measuring receiver: frequency, tuned RF level, RF power (11722A), AM, FM, distortion, modulation rate. Empty: the points that need it offer a typed reading.', column=1)
    self.sa_entry = f.row('8563E GPIB address', f.combo(self.sa_addr, (), 34, state='normal'), fill=True)
    f.note('Spectrum analyzer: harmonics and spurs (4A-11). Empty: those points offer a typed reading.', column=1)
    self.rf_entry = f.row('96270A address / resource', f.combo(self.rf_addr, (), 34, state='normal'), fill=True)
    f.note('The 96270A in power-meter mode with the R&S NRP40T sensor (4A-5, 4A-6; the sensor is UNVERIFIED). Empty: those points offer a typed reading.', column=1)
    f.rule()
    self.lf_combo = f.row('LF generator', f.combo(self.lf_model, list(LF_CHOICES), 34))
    self.lf_entry = f.row('LF generator address / resource', f.combo(self.lf_addr, (), 34, state='normal'), fill=True)
    f.note('External AM / FM (tests 3 and 6): a Keysight 33210A / 33220A / 33250A set to a sine (1 kHz, 10 kHz or 0.4 kHz) at 0.7071 V rms into High Z; its output is on only for the point. '
           'Choose None, or leave the address empty, to set your own generator at each prompt.', column=1)
    f.rule()
    self.range_combo = f.row('Generator frequency range', f.combo(self.freq_range, list(E.RANGE_CHOICES), 30, command=lambda *_a: self.on_options()))
    f.note('Some 6060A units only reach 520 MHz. Points above the chosen range are not run and are listed on the report as NOT TESTED.', column=1)
    self.thd_check = f.wide(H.checkbutton(None, 'Test 6: type THD at 10 kHz by hand', self.thd_typed, self.on_options))
    f.note('The 8902A measures distortion only at 1 kHz and 400 Hz, so THD at 10 kHz is typed from your own distortion analyzer. Untick to leave those 17 points out.')
    B.find_and_test(sh, self, 'Find instruments', self.find_instruments)

    B.action_bar(self, sh, manual=True)
    B.build_results(self, sh, SPEC['source']['note'])
    self.update_shell_sections(POINTS, lambda p: p['section_title'])


def set_choices(self, which, values):
    """The drop-down values of the 6060A ('uut'), 8902A ('rx'), 8563E ('sa'), 96270A ('rf') or LF generator ('lf') address box."""
    {'uut': self.uut_entry, 'rx': self.rx_entry, 'sa': self.sa_entry, 'rf': self.rf_entry, 'lf': self.lf_entry}[which].configure(values=values)
